#!/bin/sh
# Writes /etc/nginx/conf.d/cloudflare-realip.conf so Nginx logs (and passes
# to the app) the real visitor IP instead of Cloudflare's proxy IP.
# Re-run periodically (see Deployment/README.md) as Cloudflare's ranges change.
set -eu

OUT=/etc/nginx/conf.d/cloudflare-realip.conf
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

{
  echo "# Generated by update-cloudflare-ips.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  for list in ips-v4 ips-v6; do
    curl -fsS "https://www.cloudflare.com/$list" | while read -r range; do
      [ -n "$range" ] && echo "set_real_ip_from $range;"
    done
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"

# Refuse to install an empty list (e.g. if the download failed).
grep -q set_real_ip_from "$TMP" || { echo "No ranges downloaded" >&2; exit 1; }

install -m 644 "$TMP" "$OUT"
nginx -t && systemctl reload nginx
echo "Updated $OUT"
